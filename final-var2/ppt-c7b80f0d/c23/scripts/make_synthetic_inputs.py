# -*- coding: utf-8 -*-
"""make_synthetic_inputs.py — generate synthetic test fixtures at RUNTIME.

Part of the "paper-to-academic-ppt" Skill (ppt-c7b80f0d, efficiency-3).

Why runtime generation
----------------------
The runtime contract allows only UTF-8 text Skill resources, so no .png / .pdf /
.pptx fixture may travel inside this package. Anything the smoke tests need is
authored here instead:

* ``fig-placeholder.png`` — a pure *geometric* placeholder frame (border +
  diagonals + an explicit "NOT RESEARCH DATA" label). It exists to exercise the
  figure-embedding path and to show what "no real figure available" looks like.
  It deliberately contains **no axes, no numbers and no bars**, so it can never
  be mistaken for a research result.
* ``synthetic-two-page.pdf`` — a two-page PDF with plain ASCII text, used to
  exercise ``assetkit.extract_pdf`` (fitz -> pypdf -> pdfplumber fallbacks).
  Built with PyMuPDF when available, else matplotlib's PdfPages.
* ``synth-report.json`` — an honest record of what was generated, with which
  backend, and what was skipped and why.

Nothing here is scientific data: the text is filler and the image is a frame.

Usage
-----
    python make_synthetic_inputs.py [--out DIR]

Exit codes: 0 = at least one fixture generated; 2 = none could be generated
(missing backends) — callers must record that instead of pretending.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL_DIR = os.path.dirname(HERE)

PLACEHOLDER_LINES = [
    "FIGURE PLACEHOLDER (synthetic, generated at runtime)",
    "NOT RESEARCH DATA / 非论文原图 / 非实验数据",
    "used only to exercise the figure-embedding path",
]
PDF_PAGES = [
    ("Synthetic Fixture - Page 1 of 2",
     ["This PDF is generated at runtime by scripts/make_synthetic_inputs.py.",
      "It contains no research content: the sentences are filler text whose only",
      "purpose is to give the PDF extractor something real to parse, so that",
      "assetkit.extract_pdf can be smoke-tested without shipping a binary."]),
    ("Synthetic Fixture - Page 2 of 2",
     ["Page markers are expected to appear as [PAGE 1] / [PAGE 2] in the",
      "extracted text file. Numbers and figure references written here are",
      "invented placeholders (Fig. 1, Table 1) and must never be quoted as",
      "evidence of anything."]),
]


def _placeholder_png(path):
    """Pure geometric placeholder frame via PIL. Returns a record dict."""
    try:
        from PIL import Image, ImageDraw, ImageFont
    except Exception as exc:
        return {"file": None, "reason": "Pillow not importable: %s" % exc}
    try:
        font_path = None
        try:
            from preview import find_fonts
            font_path = find_fonts().get("font_path")
        except Exception:
            font_path = None
        W, H = 960, 540
        img = Image.new("RGB", (W, H), (242, 247, 252))
        d = ImageDraw.Draw(img)
        d.rectangle([12, 12, W - 13, H - 13], outline=(46, 116, 181), width=4)
        d.line([12, 12, W - 13, H - 13], fill=(46, 116, 181), width=2)
        d.line([W - 13, 12, 12, H - 13], fill=(46, 116, 181), width=2)
        try:
            small = ImageFont.truetype(font_path, 18) if font_path else ImageFont.load_default(size=18)
            big = ImageFont.truetype(font_path, 26) if font_path else ImageFont.load_default(size=26)
        except Exception:
            small = ImageFont.load_default(size=18)
            big = ImageFont.load_default(size=26)
        y = 24
        for i, line in enumerate(PLACEHOLDER_LINES):
            d.text((36, y), line, font=big if i == 1 else small, fill=(31, 78, 121))
            y += 40
        d.text((36, H - 60), "generated by scripts/make_synthetic_inputs.py",
               font=small, fill=(120, 120, 120))
        img.save(path, "PNG")
        return {"file": path, "bytes": os.path.getsize(path), "tool": "Pillow",
                "font_path": font_path, "w": W, "h": H,
                "note": "geometric placeholder only — intentionally no axes/numbers"}
    except Exception as exc:  # noqa: BLE001
        return {"file": None, "reason": "placeholder png failed: %s" % exc}


def _synthetic_pdf(path):
    """Two-page ASCII PDF via PyMuPDF, else matplotlib PdfPages."""
    # 1) PyMuPDF
    try:
        import fitz
        doc = fitz.open()
        for title, lines in PDF_PAGES:
            page = doc.new_page()
            page.insert_text((72, 90), title, fontsize=16)
            y = 130
            for ln in lines:
                page.insert_text((72, y), ln, fontsize=11)
                y += 20
        doc.save(path)
        doc.close()
        return {"file": path, "bytes": os.path.getsize(path), "tool": "pymupdf",
                "pages": len(PDF_PAGES)}
    except Exception as exc:  # noqa: BLE001
        first_err = "pymupdf: %s" % exc
    # 2) matplotlib
    try:
        import matplotlib
        matplotlib.use("Agg")
        from matplotlib.backends.backend_pdf import PdfPages
        import matplotlib.pyplot as plt
        with PdfPages(path) as pdf:
            for title, lines in PDF_PAGES:
                fig = plt.figure(figsize=(8.5, 11))
                fig.text(0.10, 0.92, title, fontsize=15)
                y = 0.87
                for ln in lines:
                    fig.text(0.10, y, ln, fontsize=10)
                    y -= 0.035
                pdf.savefig(fig)
                plt.close(fig)
        return {"file": path, "bytes": os.path.getsize(path), "tool": "matplotlib",
                "pages": len(PDF_PAGES), "first_error": first_err}
    except Exception as exc:  # noqa: BLE001
        return {"file": None,
                "reason": "%s; matplotlib: %s" % (first_err, exc)}


def build(out_dir):
    out_dir = os.path.abspath(out_dir)
    report = {
        "out_dir": out_dir,
        "generated": [],
        "skipped": [],
        "status": "ok",
        "notice": ("synthetic fixtures generated at runtime; they are placeholders, "
                   "not research data, and are not part of the Skill's text resources"),
    }
    try:
        os.makedirs(out_dir, exist_ok=True)
    except Exception as exc:  # noqa: BLE001 — read-only skill dir must not crash the caller
        report["status"] = "unavailable"
        report["skipped"].append({"kind": "out_dir",
                                  "reason": "cannot create output directory: %s" % exc})
        return report
    png = _placeholder_png(os.path.join(out_dir, "fig-placeholder.png"))
    (report["generated"] if png.get("file") else report["skipped"]).append(
        dict(png, kind="placeholder_png"))
    pdf = _synthetic_pdf(os.path.join(out_dir, "synthetic-two-page.pdf"))
    (report["generated"] if pdf.get("file") else report["skipped"]).append(
        dict(pdf, kind="synthetic_pdf"))
    if not report["generated"]:
        report["status"] = "unavailable"
    rep_path = os.path.join(out_dir, "synth-report.json")
    with open(rep_path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=2)
    report["report_file"] = rep_path
    return report


def main(argv=None):
    import cli_io
    cli_io.harden_console()
    ap = argparse.ArgumentParser(description="generate synthetic test fixtures at runtime")
    ap.add_argument("--out", default=os.path.join(SKILL_DIR, "examples", "generated"),
                    help="output directory (default: <skill>/examples/generated)")
    args = ap.parse_args(argv)
    rep = build(args.out)
    print(json.dumps(rep, ensure_ascii=False, indent=2))
    if rep["status"] != "ok":
        print("WARNING: no fixture could be generated — record this instead of "
              "pretending the fixture exists", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
