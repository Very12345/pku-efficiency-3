# -*- coding: utf-8 -*-
"""Editable, layered SVG writer.

Produces a *real* editable source file, not a flattened bitmap:
  - one <g id="layer:..."> group per semantic layer
    (background, panels, entities, relations, data, legend, annotations);
  - every element carries provenance attributes:
        data-entity-id / data-role / data-src / data-panel
    so any arrow, color, number or label can be traced back to its source;
  - text is real <text> elements (selectable/editable in Inkscape/Illustrator)
    with a portable font-family fallback chain, not converted to paths;
  - <title>/<desc>/<metadata> carry skill version + build id.

Pure standard library (xml.etree + xml.dom.minidom) -> runs anywhere.
"""
from __future__ import annotations

import os
import xml.etree.ElementTree as ET
from xml.dom import minidom

from common import (SKILL_VERSION, sha256_bytes, write_text)


def _point_str(points) -> str:
    return " ".join(f"{round(x,2)},{round(y,2)}" for x, y in points)


def _arrowhead(x1, y1, x2, y2, size=10.0):
    import math
    dx, dy = x2 - x1, y2 - y1
    length = math.hypot(dx, dy) or 1.0
    ux, uy = dx / length, dy / length
    px, py = -uy, ux
    base_x, base_y = x2 - ux * size, y2 - uy * size
    return [(base_x + px * size * 0.45, base_y + py * size * 0.45),
            (x2, y2),
            (base_x - px * size * 0.45, base_y - py * size * 0.45)]


def _font(size: float, bold: bool):
    return f"{size:g}", "bold" if bold else "normal"


class SvgBuilder:
    def __init__(self, spec: dict):
        self.spec = spec
        self.root = None
        self.doc = None

    # ------------------------------------------------------------------
    def build_str(self) -> str:
        w, h = self.spec["width"], self.spec["height"]
        root = ET.Element("svg", {
            "xmlns": "http://www.w3.org/2000/svg",
            "xmlns:xlink": "http://www.w3.org/1999/xlink",
            "width": f"{w:g}px", "height": f"{h:g}px",
            "viewBox": f"0 0 {w:g} {h:g}",
            "role": "img",
            "aria-label": self.spec.get("title") or "graphical abstract",
        })
        title_el = ET.SubElement(root, "title")
        title_el.text = self.spec.get("title") or "Graphical Abstract"
        desc = ET.SubElement(root, "desc")
        desc.text = ("Editable source. Text stays editable; each element "
                     "carries data-src provenance. Generated by the "
                     "graphical-abstract skill (pku-efficiency-3). Do not "
                     "flatten to paths if editing is required.")
        meta = ET.SubElement(root, "metadata")
        ET.SubElement(meta, "skill").text = f"graphical-abstract {SKILL_VERSION}"
        build_id = sha256_bytes(str(self.spec).encode("utf-8"))[:16]
        ET.SubElement(meta, "build_id").text = build_id
        ET.SubElement(meta, "case_id").text = str(self.spec.get("case_id") or "")

        for layer in self.spec["layers"]:
            g = ET.SubElement(root, "g", {"id": f"layer:{layer}", "data-layer": layer})
            lroot = g
            for el in self.spec["elements"]:
                if el.get("layer") != layer:
                    continue
                lroot.append(self._element(el))

        self.root = root
        rough = ET.tostring(root, encoding="unicode")
        pretty = minidom.parseString(rough).toprettyxml(indent="  ")
        # minidom re-emits its own xml decl; keep one clean header
        lines = pretty.splitlines()
        header = '<?xml version="1.0" encoding="UTF-8"?>'
        return header + "\n" + "\n".join(lines[1:])

    # ------------------------------------------------------------------
    def _element(self, el) -> ET.Element:
        kind = el["kind"]
        attrs = self._attrs(el)
        if kind == "rect":
            return ET.Element("rect", attrs)
        if kind == "roundrect":
            a = dict(attrs)
            a["rx"] = a["ry"] = f"{float(el['r'] or 6):g}"
            return ET.Element("rect", a)
        if kind == "circle":
            return ET.Element("circle", {
                **attrs, "cx": f"{el['cx']:g}", "cy": f"{el['cy']:g}", "r": f"{el['r']:g}"})
        if kind == "polygon":
            return ET.Element("polygon", {**attrs, "points": _point_str(el["points"])})
        if kind == "line":
            return ET.Element("line", {
                **attrs, "x1": f"{el.get('x1', 0):g}", "y1": f"{el.get('y1', 0):g}",
                "x2": f"{el.get('x2', 0):g}", "y2": f"{el.get('y2', 0):g}"})
        if kind == "arrow":
            x1, y1, x2, y2 = (float(el.get(k, 0)) for k in ("x1", "y1", "x2", "y2"))
            head = _arrowhead(x1, y1, x2, y2, size=float(el.get("head_size", 10)))
            g = ET.Element("g", {"data-role": el.get("role", "arrow")})
            ln = ET.SubElement(g, "line", {
                "x1": f"{x1:g}", "y1": f"{y1:g}", "x2": f"{x2:g}", "y2": f"{y2:g}",
                "stroke": el.get("stroke", "#888888"),
                "stroke-width": f"{float(el.get('stroke_width', 2)):g}"})
            poly = ET.SubElement(g, "polygon", {
                "points": _point_str(head),
                "fill": el.get("stroke", "#888888"), "stroke": "none"})
            return g
        if kind == "text":
            x, y = float(el.get("x", 0)), float(el.get("y", 0))
            font_size, weight = _font(float(el.get("font_size", 12)), bool(el.get("bold")))
            t = ET.Element("text", {
                **attrs, "x": f"{x:g}", "y": f"{y:g}",
                "font-family": self.spec["font_family"], "font-size": f"{font_size}px",
                "font-weight": weight,
                "fill": el.get("fill", "#333333"),
                "text-anchor": "start", "xml:space": "preserve"})
            t.text = str(el.get("text") or "")
            return t
        return ET.Element("g", attrs)

    # ------------------------------------------------------------------
    def _attrs(self, el) -> dict:
        a = {"data-role": str(el.get("role") or "")}
        fid = el.get("entity_id")
        if fid:
            a["data-entity-id"] = fid
        src = el.get("src")
        if src:
            a["data-src"] = str(src)
        panel = el.get("panel")
        if panel:
            a["data-panel"] = panel
        lk = el.get("legend_key")
        if lk:
            a["data-legend-key"] = lk
        fill = el.get("fill")
        if fill:
            a["fill"] = fill
        else:
            a["fill"] = "none"
        stroke = el.get("stroke")
        if stroke:
            a["stroke"] = stroke
        a["stroke-width"] = f"{float(el.get('stroke_width', 1)):g}"
        return a


def write(spec: dict, path: str) -> str:
    body = SvgBuilder(spec).build_str()
    write_text(path, body)
    return path