def main(argv=None):
    ap = argparse.ArgumentParser(
        description="缺依赖降级链实测（受控导入拦截 + 外部命令缺失，逐探针真跑主流程/子工具）")
    ap.add_argument("--skill-root", default=DEFAULT_ROOT,
                    help="技能根目录（默认：本脚本上一级）")
    ap.add_argument("--out", default=None,
                    help="输出目录（**必须在技能包之外**）；报告写到 <out>/degrade-matrix.json")
    ap.add_argument("--only", default=None, help="逗号分隔的探针 id，如 G01,G03c")
    ap.add_argument("--list", action="store_true", help="只列探针表，不执行")
    ap.add_argument("--json", action="store_true", help="stdout 也打印 JSON 报告")
    ap.add_argument("--quiet", action="store_true", help="只打印汇总")
    ap.add_argument("--keep", action="store_true", help="保留 scratch（排查用）")
    ap.add_argument("--timeout", type=int, default=180, help="每个探针的超时秒数")
    args = ap.parse_args(argv)

    skill_root = os.path.abspath(args.skill_root)
    if not os.path.isdir(os.path.join(skill_root, "scripts")):
        log("FATAL: %s 不像技能根（缺 scripts/）", skill_root)
        return 2

    probes = PROBES
    if args.only:
        want = {x.strip().upper() for x in args.only.split(",") if x.strip()}
        probes = [p for p in PROBES if p["id"].upper() in want]
        if not probes:
            log("FATAL: --only 没有匹配到任何探针：%s", args.only)
            return 2

    if args.list:
        print("探针表（%d 条）：" % len(probes))
        for p in probes:
            tgt = "、".join(p["blocks"]) or ("LibreOffice CLI" if p.get("path_mode") == "minimal" else "(无)")
            print("  %-5s 缺: %-46s %s" % (p["id"], tgt, p["name"]))
            print("        %s" % p["why"])
        print("说明：每条探针都只在包外副本里生效；退出码 0 = 每条都留下可解释的实测形态，"
              "1 = 有探针静默")
        return 0

    if not args.out:
        log("FATAL: --out 必填（报告要写在包外）")
        return 2
    out_dir = os.path.abspath(args.out)
    if in_root(out_dir, skill_root):
        log("FATAL: --out 不能指向技能包内部（%s）；本脚本只动包外副本", out_dir)
        return 2
    os.makedirs(out_dir, exist_ok=True)

    records = []
    for i, p in enumerate(probes, 1):
        if not args.quiet:
            log("[%d/%d] %s %s", i, len(probes), p["id"], p["name"])
        try:
            rec = run(p, skill_root, args)
        except Exception as exc:                       # pragma: no cover - defensive
            rec = {"id": p["id"], "name": p["name"], "missing": p["blocks"],
                   "why": p["why"], "tier": "unavailable", "silent": None,
                   "note": "runner exception: %r" % (exc,)}
        records.append(rec)
        if not args.quiet:
            log("      exit=%s status=%s tier=%s silent=%s artifacts=%s",
                rec.get("exit"), rec.get("status"), rec.get("tier"),
                rec.get("silent"), rec.get("artifacts"))

    silent = [r for r in records if r.get("silent")]
    unavailable = [r for r in records if r.get("tier") == "unavailable"]
    minimal_env = _minimal_env(records)
    summary = {
        "probes": len(records),
        "silent": len(silent),
        "silent_ids": [r["id"] for r in silent],
        "tiers": _count(r.get("tier") for r in records),
        "unavailable_ids": [r["id"] for r in unavailable],
        "no_effect_ids": [r["id"] for r in records if r.get("tier") == "full"
                          and not r.get("on_runtime_path")],
        "modules_on_runtime_path": sorted({b for r in records if r.get("on_runtime_path")
                                           for b in (r.get("missing") or [])}),
        "modules_not_on_runtime_path": sorted({b for r in records
                                               if not r.get("on_runtime_path")
                                               for b in (r.get("missing") or [])}),
    }
    report = {
        "schema": "sse-degrade-matrix/1",
        "skill_root": os.path.basename(skill_root),
        "python": sys.version.split()[0],
        "interception": "sitecustomize.py + sys.meta_path MetaPathFinder + PYTHONPATH"
                        "（等价于目标机没装该库；不改被测代码）",
        "probes": records,
        "silent_probes": [{"id": r["id"], "name": r["name"], "tier": r.get("tier"),
                           "why": "注入的缺失在运行路径上，但退出码 0 且 fail/warn/"
                                  "uncertainty 全空"} for r in silent],
        "unavailable_features": [
            {"id": r["id"], "missing": r.get("missing"),
             "what_breaks": _what_breaks(r), "recovery": _recovery(r)}
            for r in records if r.get("tier") == "unavailable"],
        "minimal_env": minimal_env,
        "summary": summary,
    }
    rp = os.path.join(out_dir, "degrade-matrix.json")
    dump_json(rp, report)

    if not args.quiet:
        print("")
        print("  %-5s %-34s %-6s %-9s %-17s %-6s %s"
              % ("id", "missing", "exit", "status", "tier", "silent", "artifacts"))
        for r in records:
            print("  %-5s %-34s %-6s %-9s %-17s %-6s %s"
                  % (r["id"], ("、".join(r.get("missing") or []) or "(none)")[:34],
                     r.get("exit"), str(r.get("status"))[:9], r.get("tier"),
                     r.get("silent"), ",".join(r.get("artifacts") or [])[:40]))
    log("probes=%d tiers=%s silent=%d(%s)",
        summary["probes"], json.dumps(summary["tiers"], ensure_ascii=False),
        summary["silent"], ",".join(summary["silent_ids"]) or "-")
    log("wrote %s", rp)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=1))
    return 0 if summary["silent"] == 0 else 1


def _what_breaks(rec):
    if rec.get("subtool"):
        return "子工具在缺该依赖时无法完成（见 exit / 读数）"
    if rec.get("status") == "failed":
        return "整条流水线在该探针下不可用：只写出 failed 的 result.json，没有图稿/导出件"
    if rec.get("status") == "partial":
        return "产物不完整（见 artifacts 列表）"
    return "无 result.json：连失败记录都没写出来"


def _recovery(rec):
    mods = [m for m in (rec.get("missing") or []) if m not in ("LibreOffice CLI",)]
    if mods:
        return "pip install " + " ".join(sorted(mods))
    return "无需安装（该探针的缺失项既不在运行路径上，也不需要恢复）"


def _count(values):
    out = {}
    for v in values:
        out[str(v)] = out.get(str(v), 0) + 1
    return out


def _minimal_env(records):
    """「最小可用环境」清单：模块 → 是否必需 → 证据 → 回退/恢复。"""
    rows = []
    seen = set()
    for r in records:
        for m in (r.get("missing") or []):
            if m in seen:
                continue
            seen.add(m)
            on_path = bool(r.get("on_runtime_path"))
            rows.append({
                "module": m,
                "required": ("yes" if r.get("tier") == "unavailable" and on_path else
                             ("conditional" if on_path else "no")),
                "why": r.get("why"),
                "evidence_probe": r["id"],
                "observed_tier": r.get("tier"),
                "observed_exit": r.get("exit"),
                "observed_status": r.get("status"),
                "fallback_or_recovery": _recovery(r),
            })
    order = {"yes": 0, "conditional": 1, "no": 2}
    rows.sort(key=lambda x: (order.get(x["required"], 3), x["module"]))
    return rows


if __name__ == "__main__":
    sys.exit(main())
