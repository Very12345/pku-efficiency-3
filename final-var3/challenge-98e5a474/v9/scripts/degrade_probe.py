def log(msg, *args):
    print("[dg] " + (msg % args if args else msg), flush=True)


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def write_bytes(path, blob):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(blob)


def load_json(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def dump_json(path, obj):
    write_text(path, json.dumps(obj, ensure_ascii=False, indent=2) + "\n")


def tail(text, n=5, width=180):
    lines = [l for l in (text or "").splitlines() if l.strip()]
    return [l[:width] for l in lines[-n:]]


def in_root(path, root):
    a = os.path.abspath(path).rstrip("\\/").lower()
    b = os.path.abspath(root).rstrip("\\/").lower()
    return a == b or a.startswith(b + os.sep) or a.startswith(b + "/")


def make_text_pdf(text="sample material for the degrade chain probe\n",
                  compress=True):
    """生成一个**最小可用**的文本 PDF（可选 Flate 压缩，用来逼出 stdlib 回退）。

    只用标准库：PDF 结构 + 一个内容流（可 zlib 压缩）。不依赖任何 PDF 库，
    正好用来测"没有第三方 PDF 库时还能不能抽到字"。
    """
    content = ("BT /F1 12 Tf 40 720 Td (%s) Tj ET"
               % text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)"))
    raw = content.encode("latin-1")
    if compress:
        stream = zlib.compress(raw)
        filt = b" /Filter /FlateDecode"
    else:
        stream = raw
        filt = b""
    objs = []
    objs.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    objs.append(b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>")
    objs.append(b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
                b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>")
    objs.append(b"<< /Length " + str(len(stream)).encode() + filt + b" >>\nstream\n"
                + stream + b"\nendstream")
    objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += str(i).encode() + b" 0 obj\n" + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 " + str(len(objs) + 1).encode() + b"\n0000000000 65535 f \n"
    for off in offsets:
        out += ("%010d 00000 n \n" % off).encode()
    out += (b"trailer\n<< /Size " + str(len(objs) + 1).encode()
            + b" /Root 1 0 R >>\nstartxref\n" + str(xref).encode() + b"\n%%EOF\n")
    return bytes(out)


