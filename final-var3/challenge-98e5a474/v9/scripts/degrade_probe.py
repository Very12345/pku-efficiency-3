"""degrade_probe.py -- 缺依赖降级链实测（可运行的受控导入拦截矩阵）。

本脚本回答一个工程问题，而且只回答它：

> 当目标机**缺**某个库（或某个外部命令）时，本技能**还剩什么**？
> 主流程退出码是什么、`status` 变成什么、还写不写 `result.json`、
> 产物少了哪几件、`uncertainty` 里有没有痕迹、有没有"静默降级"？

做法是**受控导入拦截**（不是 patch 被测代码）：在包外 scratch 里生成一个
`sitecustomize.py`，用 `sys.meta_path` 上的 MetaPathFinder 让指定顶层模块
`import` 时报 `ModuleNotFoundError`，再用 `PYTHONPATH=<scratch fx>` 启动被测脚本。
这在语义上**等价于目标机没装该库**，同时保证：

1. **只动包外副本**：整包复制到 tempfile.mkdtemp() 再跑；`--out` 指包内直接拒绝；
2. **不改被测逻辑**：被测脚本的 CLI 参数与退出码语义一个字都没动；
3. **不伪造数据**：记录的是子进程真实 returncode 与真实 `result.json` 字段；
   拿不到产物就记「无产物」，不做推断；
4. **静默降级要判出来**：出了依赖问题却"退出码 0 + 无 fail/warn + `uncertainty`
   里没有任何痕迹" ⇒ 记 `silent=True`，并让退出码非零（这是真缺陷）。

覆盖的探针（可用 `--list` 看全表）：`matplotlib` / `PIL` / `numpy` / `yaml` /
`pptx` / `lxml` / PDF 库族（fitz+pypdf+PyPDF2）/ `reportlab` / LibreOffice CLI /
"只留 matplotlib+PIL"（其余可选全缺）；另有三条**子工具**探针：PDF 文本抽取的
stdlib 回退、题集执行器的 XML 后端回退、reportlab 缺失下的主流程。

用法（建议在包外运行，产物写到包外）：

    python scripts/degrade_probe.py --skill-root <技能根> --out <包外目录>
    python scripts/degrade_probe.py --skill-root . --out /tmp/dg --list
    python scripts/degrade_probe.py --skill-root . --out /tmp/dg --only G01,G03
    python scripts/degrade_probe.py --skill-root . --out /tmp/dg --json --quiet

退出码：0 = 每条探针都留下可解释的实测形态（含"缺依赖 ⇒ 如实失败"）；
1 = 有探针**静默**（出问题但无任何痕迹）；2 = 参数或环境错误。
"""

