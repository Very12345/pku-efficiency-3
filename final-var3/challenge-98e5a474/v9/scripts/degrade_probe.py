class Scratch(object):
    def __init__(self, skill_root, pid):
        self.root = tempfile.mkdtemp(prefix="sse-degrade-%s-" % pid)
        self.pkg = os.path.join(self.root, "pkg")
        self.fx = os.path.join(self.root, "fx")
        self.out = os.path.join(self.root, "out")
        shutil.copytree(skill_root, self.pkg,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        os.makedirs(self.fx, exist_ok=True)
        os.makedirs(self.out, exist_ok=True)
        self.notes = {}

    def env(self, blocks, path_mode=None):
        env = dict(os.environ)
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        if blocks:
            write_text(os.path.join(self.fx, "sitecustomize.py"),
                       _BLOCKER_TEMPLATE.format(block=list(blocks),
                                                msg="injected absence"))
            prev = env.get("PYTHONPATH", "")
            env["PYTHONPATH"] = self.fx + (os.pathsep + prev if prev else "")
        if path_mode == "minimal":
            env["PATH"] = os.path.dirname(PY) or env.get("PATH", "")
        return env


